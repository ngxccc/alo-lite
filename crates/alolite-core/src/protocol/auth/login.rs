/// PasswordCipher (class `N`) — `re-notes/01-login.md` §2.2.
///
/// Encrypts user credentials for `POST /api/login/loginByPasswv2` using Zalo PC's custom
/// double-hash key derivation and reversed password padding.
///
/// # Key Derivation Algorithm
/// 1. Compute SHA-256 hash of `"{PW_KEY}-{phone}-{imei}-{salt}"` with fixed `PW_KEY = "9fc5vEW3"`.
/// 2. Extract uppercase hex digest and partition characters by index parity:
///    - `even`: characters at index 0, 2, 4, ...
///    - `odd`: characters at index 1, 3, 5, ...
/// 3. Assemble the 32-byte AES key `enk`:
///    `enk = even[0..16] + reverse(odd)[0..16]`
/// 4. Construct plaintext by concatenating `salt` with the reversed password string:
///    `plaintext = salt + reverse(password)`
/// 5. Encrypt with AES-256-CBC with an all-zero IV (`[0u8; 16]`) and PKCS#7 padding.
/// 6. Return Base64-encoded ciphertext.
///
/// # Arguments
/// * `phone` - The phone number entered by the user (with country code or local).
/// * `imei` - The device identity string (`s.imei`).
/// * `password` - The raw user password (plaintext).
/// * `salt` - 8-character random alphanumeric salt generated by [`random_salt`].
///
/// # Returns
/// Base64-encoded ciphertext suitable for the `password` field of `loginByPasswv2`.
///
/// # Errors
/// Returns an error if AES-256-CBC encryption fails.
pub fn encrypt_password(phone: &str, imei: &str, password: &str, salt: &str) -> Result<String> {
    const PW_KEY: &str = "9fc5vEW3";

    let mut h = Sha256::new();
    h.update(format!("{PW_KEY}-{phone}-{imei}-{salt}").as_bytes());
    let hex = h.finalize().iter().fold(String::new(), |mut acc, b| {
        use std::fmt::Write;
        let _ = write!(acc, "{b:02X}");
        acc
    });

    let even: Vec<char> = hex.chars().step_by(2).collect();
    let odd: Vec<char> = hex.chars().skip(1).step_by(2).collect();
    let enk: String =
        even[..16].iter().collect::<String>() + &odd.iter().rev().take(16).collect::<String>();

    let mut plain = salt.to_string();
    plain.extend(password.chars().rev());

    crate::crypto::encode_aes(enk.as_bytes(), &plain)
}

/// Generate an 8-character random alphanumeric salt for [`encrypt_password`].
///
/// # Algorithm
/// Uses a 64-bit Linear Congruential Generator (LCG) seeded from system time nanoseconds
/// and process ID:
/// `seed = (seed * 6364136223846793005 + 1442695040888963407)`
/// selecting characters from `b"abcdefghijklmnopqrstuvwxyz0123456789"`.
///
/// # Returns
/// An 8-character ASCII string suitable for salt generation in Zalo PasswordCipher.
pub fn random_salt() -> String {
    use std::time::{SystemTime, UNIX_EPOCH};
    const ALPHA: &[u8] = b"abcdefghijklmnopqrstuvwxyz0123456789";
    let mut seed = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(1)
        ^ ((std::process::id() as u64) << 17);
    let mut out = String::with_capacity(8);
    for _ in 0..8 {
        seed = seed
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        out.push(ALPHA[(seed >> 33) as usize % ALPHA.len()] as char);
    }
    out
}

/// Fetch initial server configuration and domain gates (`GET /api/login/getServerInfo`).
///
/// \[O\] Bundle flow (`getServerInfo`):
/// Unauthenticated pre-login request that informs the client whether parameter encryption
/// (`enable_encrypt_param`) and trusted-device verification are enabled, and returns the
/// initial REST and long-polling endpoint mapping.
///
/// # Arguments
/// * `s` - Active [`Session`] supplying IMEI, computer name, and auth domain.
///
/// # Outbound Request
/// Query parameters signed with `signkey = sign_key("getserverinfo", params)`:
/// - `imei`: Device identifier.
/// - `type`: Client API type (`ZPW_TYPE = 30`).
/// - `client_version`: Client version code (`ZPW_VER = 693`).
/// - `computer_name`: Host machine name.
/// - `sp_mtn`: `-1` (maintenance bypass flag).
/// - `bkt`: `-1` (bucket flag).
///
/// # Wire Response Example
/// ```json
/// {
///   "error_code": 0,
///   "error_message": "Successful",
///   "data": {
///     "zpw_chts_new": ["https://p4-msg-chat.zaloapp.com"],
///     "zpw_ctrs_new": ["https://p4-ctl-chat.zaloapp.com"],
///     "zpw_ws": ["wss://ws1-msg.chat.zalo.me"],
///     "zpw_service_map_v3": { "chat": ["https://tt-chat3-wpa.api.zaloapp.com"] },
///     "setttings": {
///       "authen": {
///         "trusted_device": { "qr_format_trust_device": 1 }
///       }
///     }
///   }
/// }
/// ```
///
/// # Errors
/// Returns an error if the network request fails or server returns a transport error.
pub async fn get_server_info(s: &Session) -> Result<Value> {
    let p = obj(&[
        ("imei", json!(s.imei)),
        ("type", json!(ZPW_TYPE)),
        ("client_version", json!(ZPW_VER)),
        ("computer_name", json!(s.computer_name)),
        ("sp_mtn", json!(-1)),
        ("bkt", json!(-1)),
    ]);

    let sig = if let Value::Object(ref m) = p {
        crate::crypto::sign_key("getserverinfo", m)
    } else {
        String::new()
    };
    let query = flatten_query(&p);

    let url = format!(
        "{}/api/login/getServerInfo?{query}&signkey={sig}",
        s.domains.auth
    );
    s.get(&url).await
}

/// Authenticate using phone number and password via v1 diagnostic protocol (`POST /api/login/loginByPassw`).
///
/// \[O\] Exact bundle flow (`signInPassword`):
/// Plain parameters with `signkey = sign_key("loginbypassw", params)` sent via `params=<urlencode(json)>`.
/// Note: On production Zalo accounts, the server rejects v1 requests with error `18060 ("Invalid encryption protocol")`.
/// This function is maintained as a clean diagnostic and test path to inspect server responses
/// without the v2 encryption layer.
///
/// # Arguments
/// * `s` - Active [`Session`].
/// * `phone` - User phone number.
/// * `password` - Plaintext user password.
///
/// # Returns
/// [`crate::protocol::wire::ActionAck`].
///
/// # Errors
/// Returns an error if transport fails or server returns a non-zero `error_code` (e.g. `18060`).
pub async fn login_by_password_v1(
    s: &mut Session,
    phone: &str,
    password: &str,
) -> Result<crate::protocol::wire::ActionAck> {
    let mut o = obj(&[
        ("phone_num", json!(phone)),
        ("password", json!(password)),
        ("cptch_token", json!("")),
        ("cptch_answer", json!("")),
        ("type", json!(ZPW_TYPE)),
        ("client_version", json!(ZPW_VER)),
        ("computer_name", json!(s.computer_name)),
        ("imei", json!(s.imei)),
        ("ref", json!(crate::endpoints::CHAT_ORIGIN)),
    ]);

    let sig = if let Value::Object(ref m) = o {
        crate::crypto::sign_key("loginbypassw", m)
    } else {
        String::new()
    };
    if let Value::Object(ref mut m) = o {
        m.insert("signkey".into(), json!(sig));
    }

    let url = format!("{}/api/login/loginByPassw", s.domains.auth);
    let form = format!("params={}", urlencode(&o.to_string()));
    let resp = s.post_form(&url, form).await?;

    let env = LoginResponseWireData::from_value(&resp);
    let code = env.code();
    if code != 0 {
        anyhow::bail!("v1 login error {code}: {}", env.message());
    }
    if let Some(cfg) = &env.data {
        apply_login_config(s, cfg);
    }
    Ok(crate::protocol::wire::ActionAck::from_wire(&resp))
}

/// Authenticate using phone number and password via v2 protocol (`POST /api/login/loginByPasswv2`).
///
/// \[O\] Exact bundle flow (`signInPasswordV2` in `default-login-main-startup-shared-worker-znotification.*.js`):
/// 1. Generates 8-character random salt via [`random_salt`].
/// 2. Derives AES key and encrypts password via [`encrypt_password`].
/// 3. Assembles signed payload `g` containing phone, country code, encrypted password, salt,
///    machine metadata, and stored logged UINs.
/// 4. Encrypts payload with [`ParamCipher`] v2 using tag `"loginbypasswv2"`.
/// 5. Appends `ref = https://chat.zalo.me` AFTER signing (excluded from `signkey`).
/// 6. Sends `POST` form request and decrypts response with the derived AES key.
/// 7. Parses [`LoginResponseWireData`], applies credentials via [`apply_login_config`], and
///    returns [`crate::protocol::wire::ActionAck`].
///
/// # Arguments
/// * `s` - Active [`Session`].
/// * `phone` - Phone number (e.g. `"0901234567"` or country-code formatted).
/// * `password` - Plaintext user password.
/// * `iso` - ISO country code (e.g. `"VN"`).
///
/// # Returns
/// [`crate::protocol::wire::ActionAck`] indicating success or server failure code.
///
/// # Errors
/// Returns an error if encryption fails, HTTP transport fails, or server returns a non-zero error code:
/// - `18060`: Invalid encryption protocol (ParamCipher v2 required).
/// - `18022`: Invalid signature.
/// - `18024`: Incorrect phone number or password.
/// - `18012` / `18013`: Verification / Captcha challenge required.
pub async fn login_by_password(
    s: &mut Session,
    phone: &str,
    password: &str,
    iso: &str,
) -> Result<crate::protocol::wire::ActionAck> {
    let salt = random_salt();
    let pwd = encrypt_password(phone, &s.imei, password, &salt)?;
    let client_time = unix_now();

    // Field order and set must match `g` exactly — the signkey hashes sorted values.
    //
    // `logged_uids` is passed as the caller's value; the real client sends the stored
    // uid list, and `null` when there is none. Sending the string "[]" changes both the
    // signed payload and what the server expects to see.
    let payload = obj(&[
        ("phone_num", json!(phone)),
        ("iso_country_code", json!(iso)),
        ("password", json!(pwd)),
        ("salt", json!(salt)),
        ("cptch_token", json!("")),
        ("cptch_answer", json!("")),
        ("make_answer", json!(0)),
        ("language", json!("en")),
        ("logged_uids", {
            let csv = s.logged_uids_csv();
            if csv.is_empty() {
                json!(null)
            } else {
                json!(csv)
            }
        }),
        ("computer_name", json!(s.computer_name)),
        ("imei", json!(s.imei)),
    ]);

    let cipher = ParamCipher::new(ZPW_TYPE, &s.imei, client_time)?;
    let body = cipher.build_body(ZPW_TYPE, ZPW_VER, &payload, "loginbypasswv2")?;

    // Signed set only — no `enk`, no `ref` (both are outside the hash server-side).
    let query = flatten_query(&body);
    let url = format!(
        "{}/api/login/loginByPasswv2?{query}&ref={}",
        s.domains.auth,
        urlencode(crate::endpoints::CHAT_ORIGIN)
    );

    let resp = s.post_form(&url, String::new()).await?;
    let resp = s.maybe_decrypt(resp, cipher.key().as_bytes()).await;

    // Surface an error code hidden inside the encrypted envelope.
    let env = LoginResponseWireData::from_value(&resp);
    let code = env.code();
    if code != 0 {
        anyhow::bail!("login error {code}: {}", env.message());
    }

    if let Some(cfg) = &env.data {
        apply_login_config(s, cfg);
    }
    Ok(crate::protocol::wire::ActionAck::from_wire(&resp))
}

/// Flatten a JSON object into a `k=v&k=v` URL query string.
///
/// Used for unsigned query strings (e.g. `ref`) and ParamCipher v2 encrypted query envelopes.
fn flatten_query(v: &Value) -> String {
    let Some(m) = v.as_object() else {
        return String::new();
    };
    m.iter()
        .map(|(k, val)| {
            let sv = match val {
                Value::String(s) => s.clone(),
                other => other.to_string(),
            };
            format!("{}={}", k, urlencode(&sv))
        })
        .collect::<Vec<_>>()
        .join("&")
}

/// Query session authentication state and keys (`GET /api/login/getLoginInfo`).
///
/// Probes both `s.domains.auth` (`https://wpa.zaloapp.com`, where PC session cookies live) and
/// `s.domains.wpa_chat` (`https://wpa.chat.zalo.me`, where web session cookies live). Requests are
/// encrypted using [`ParamCipher`] v2 with tag `"getlogininfo"`.
///
/// # Arguments
/// * `s` - Active [`Session`] providing device metadata and HTTP client with session cookies.
///
/// # Wire Response Example
/// ```json
/// {
///   "error_code": 0,
///   "error_message": "Successful",
///   "data": {
///     "dkey": "1234567890",
///     "zpw_enk": "dGVzdF9lbmtfMzJfYnl0ZXNfbG9uZ19hZXNfa2V5IQ==",
///     "zpw_sek": "sek_token_string",
///     "send2me_id": "1234567890",
///     "display_name": "Ngọc Trần",
///     "zpw_chts_new": "https://p4-msg-chat.zaloapp.com",
///     "zpw_ctrs_new": "https://p4-ctl-chat.zaloapp.com",
///     "account": {
///       "userId": "1234567890",
///       "zpw_sek": "sek_token_string",
///       "display_name": "Ngọc Trần"
///     }
///   }
/// }
/// ```
///
/// # Errors
/// Returns an error if the network request fails across all candidate hosts or decryption fails.
pub async fn get_login_info(s: &Session) -> Result<Value> {
    let client_time = unix_now();
    let payload = obj(&[
        ("imei", json!(s.imei)),
        ("computer_name", json!(s.computer_name)),
        ("language", json!("vi")),
        ("ts", json!(client_time)),
    ]);
    let cipher = ParamCipher::new(ZPW_TYPE, &s.imei, client_time)?;
    let body = cipher.build_body(ZPW_TYPE, ZPW_VER, &payload, "getlogininfo")?;
    let query = flatten_query(&body);

    // Try both auth host (wpa.zaloapp.com, where PC session cookies live)
    // and wpa_chat (wpa.chat.zalo.me, where web session cookies live).
    let hosts = [&s.domains.auth, &s.domains.wpa_chat];
    let mut last_err = anyhow::anyhow!("get_login_info failed on all hosts");

    for host in hosts {
        let url = format!("{host}/api/login/getLoginInfo?{query}&nretry=0");
        match s.get(&url).await {
            Ok(resp) => {
                let decrypted = s.maybe_decrypt(resp, cipher.key().as_bytes()).await;
                let env = crate::protocol::wire::ErrorEnvelopeWireData::parse(&decrypted);
                if env.code() == 0 {
                    return Ok(decrypted);
                }
            }
            Err(e) => {
                last_err = e;
            }
        }
    }
    Err(last_err)
}

/// Fetch `/api/login/getServerInfo` and apply dynamic endpoint settings to `s`.
///
/// Parses the response into [`ServerInfoResponseWireData`] and applies WebSocket,
/// long-polling, and REST endpoint service maps via [`Session::apply_server_info_wire`].
///
/// # Arguments
/// * `s` - Active [`Session`] to update with dynamic server endpoints.
///
/// # Errors
/// Returns an error if the network request fails or the server returns an error.
pub async fn fetch_and_apply_server_info(s: &mut Session) -> Result<()> {
    let resp = get_server_info(s).await?;
    let env = ServerInfoResponseWireData::from_value(&resp);
    if let Some(d) = &env.data {
        s.apply_server_info_wire(d);
    }
    Ok(())
}

/// Fetch `/api/login/getLoginInfo`, apply session credentials and endpoints, and refresh `zpw_sek`.
///
/// # Flow
/// 1. Queries [`get_login_info`] to retrieve session credentials and dynamic endpoints.
/// 2. Extracts `zpw_sek` cookie token via [`crate::protocol::auth::qr::extract_zpw_sek`] and refreshes `s.zpw_sek`.
/// 3. Parses [`LoginResponseWireData`] from the decrypted JSON envelope.
/// 4. Applies credentials, UIN, session keys, and dynamic endpoint overrides via [`apply_login_config`].
///
/// # Arguments
/// * `s` - Active [`Session`] to hydrate with login credentials and endpoints.
///
/// # Errors
/// Returns an error if [`get_login_info`] fails on all candidate hosts.
pub async fn fetch_and_apply_login_info(s: &mut Session) -> Result<()> {
    let info = get_login_info(s).await?;
    if let Some(sek) = super::qr::extract_zpw_sek(&info) {
        s.set_zpw_sek(sek);
    }
    let env = LoginResponseWireData::from_value(&info);
    if let Some(cfg) = &env.data {
        apply_login_config(s, cfg);
    }
    Ok(())
}

