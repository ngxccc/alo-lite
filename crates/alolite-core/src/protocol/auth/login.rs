//! Pre-login server discovery, password authentication, and session bootstrap.
//!
//! Implements the complete Zalo PC 26.10.11 login protocol as observed in bundle module `"5NUA"`
//! and `pc-dist/lazy/default-login-main-startup-shared-worker-znotification.*.js` (reverse-engineering
//! documentation: `re-notes/01-login.md` §5):
//!
//! 1. **Server Discovery (`getServerInfo`)**: Unauthenticated pre-login probe that gates parameter
//!    encryption (`enable_encrypt_param`) and delivers the dynamic REST endpoint service map (`zpw_service_map_v3`).
//! 2. **Password Authentication (`loginByPasswv2`)**: High-security authentication using [`ParamCipher`] v2
//!    request encryption, double-hash PasswordCipher (class `N`), random salt, and machine identity.
//! 3. **Session Bootstrap & Refresh (`getLoginInfo`)**: Multi-host cookie-based session verification that
//!    retrieves account identifiers (`dkey`), session secrets (`zpw_enk`), authentication cookies (`zpw_sek`),
//!    and long-polling endpoints (`zpw_chts_new`, `zpw_ctrs_new`).

