/// Decrypted response envelope returned by `POST /api/login/loginByPasswv2` and `GET /api/login/getLoginInfo`.
///
/// # Wire Response Example
/// ```json
/// {
///   "error_code": 0,
///   "error_message": "Successful",
///   "data": {
///     "dkey": "1234567890",
///     "zpw_enk": "dGVzdF9lbmtfMzJfYnl0ZXNfbG9uZ19hZXNfa2V5IQ==",
///     "zpw_sek": "sek_abc_123"
///   }
/// }
/// ```
///
/// # Core Transformation
/// Decrypted using the derived [`ParamCipher`] AES key. Surfaces server error codes and encapsulates
/// the inner [`LoginConfigWireData`] configuration.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct LoginResponseWireData {
    #[serde(rename = "error_code")]
    pub error_code: Option<Value>,
    #[serde(rename = "error_message")]
    pub error_message: Option<Value>,
    #[serde(rename = "data")]
    pub data: Option<LoginConfigWireData>,
}

impl LoginResponseWireData {
    /// Numeric error code (`0` for success).
    pub fn code(&self) -> i64 {
        self.error_code
            .as_ref()
            .and_then(Value::as_i64)
            .unwrap_or(0)
    }

    /// Server error message.
    pub fn message(&self) -> &str {
        opt_text(self.error_message.as_ref())
    }
}

/// Login config payload (`data`) returned by `loginByPasswv2` and `getLoginInfo`.
///
/// # Wire Response Example
/// ```json
/// {
///   "dkey": "1234567890",
///   "zpw_enk": "<redacted>",
///   "zpw_sek": "<redacted>",
///   "send2me_id": "<redacted>",
///   "display_name": "Ngọc Trần",
///   "zpw_chts_new": "https://p4-msg-chat.zaloapp.com",
///   "zpw_ctrs_new": "https://p4-ctl-chat.zaloapp.com",
///   "account": { "userId": "1234567890", "zpw_sek": "<redacted>", "display_name": "Ngọc Trần" }
/// }
/// ```
///
/// # Core Transformation
/// Populates `Session::login` (`uin`, `zpw_enk`, `zpw_sek`, `display_name`, `send2me_id`) while
/// preserving already-established credentials when the new payload only carries partial fields.
/// Key priority mirrors the shipped client (`uid` > `userId` > `account.*` > `dkey`).
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct LoginConfigWireData {
    #[serde(flatten)]
    pub server_info: ServerInfoWireData,
    #[serde(rename = "uid")]
    pub uid: Option<Value>,
    #[serde(rename = "userId")]
    pub user_id: Option<Value>,
    #[serde(rename = "account")]
    pub account: Option<LoginAccountWireData>,
    #[serde(rename = "dkey")]
    pub dkey: Option<Value>,
    #[serde(rename = "zpw_enk")]
    pub zpw_enk: Option<Value>,
    #[serde(rename = "send2me_id")]
    pub send2me_id: Option<Value>,
    #[serde(rename = "zpw_sek")]
    pub zpw_sek: Option<Value>,
    #[serde(rename = "display_name")]
    pub display_name: Option<Value>,
    #[serde(rename = "settings")]
    pub settings: Option<LoginSettingsWireData>,
}

impl LoginConfigWireData {
    /// Numeric account id (`uid` > `userId` > `account.userId` > `account.uid` > `dkey`).
    pub fn dkey(&self) -> String {
        field_str(self.uid.as_ref())
            .or_else(|| field_str(self.user_id.as_ref()))
            .or_else(|| {
                let acc = self.account.as_ref()?;
                field_str(acc.user_id.as_ref()).or_else(|| field_str(acc.uid.as_ref()))
            })
            .or_else(|| field_str(self.dkey.as_ref()))
            .unwrap_or_default()
    }

    /// Encrypted secret key (`zpw_enk`).
    pub fn zpw_enk(&self) -> String {
        field_str(self.zpw_enk.as_ref()).unwrap_or_default()
    }

    /// Send-to-self conversation id.
    pub fn send2me_id(&self) -> String {
        field_str(self.send2me_id.as_ref()).unwrap_or_default()
    }

    /// Session cookie (`zpw_sek`), top level then nested under `account`.
    pub fn zpw_sek(&self) -> String {
        field_str(self.zpw_sek.as_ref())
            .or_else(|| {
                let acc = self.account.as_ref()?;
                field_str(acc.zpw_sek.as_ref())
            })
            .unwrap_or_default()
    }

    /// Display name (`account.display_name` > `display_name` > `settings.profile.name`).
    pub fn display_name(&self) -> String {
        self.account
            .as_ref()
            .and_then(|a| field_str(a.display_name.as_ref()))
            .or_else(|| field_str(self.display_name.as_ref()))
            .or_else(|| {
                let st = self.settings.as_ref()?;
                let prof = st.profile.as_ref()?;
                field_str(prof.name.as_ref())
            })
            .unwrap_or_default()
    }

    /// Long-polling chat host (`zpw_chts_new`), if non-empty.
    pub fn lp_chat(&self) -> Option<String> {
        field_str(self.server_info.zpw_chts_new.as_ref())
    }

    /// Long-polling control host (`zpw_ctrs_new`), if non-empty.
    pub fn lp_control(&self) -> Option<String> {
        field_str(self.server_info.zpw_ctrs_new.as_ref())
    }
}

/// Apply session credentials, secret keys, user display identity, and endpoint tables onto [`Session`].
///
/// Implements the credential ingestion logic following a successful `loginByPasswv2`,
/// `getLoginInfo`, or QR confirmation response.
///
/// # Arguments
/// * `s` - Active [`Session`] whose credentials, login info, and domain endpoints are updated.
/// * `typed` - Parsed [`LoginConfigWireData`] containing credentials and server configuration.
///
/// # Extracted Credentials & Priority
/// - **Account ID (`uin`)**: Resolved via `typed.dkey()` (`uid` > `userId` > `account.userId` > `account.uid` > `dkey`).
///   Recorded into `s.known_uids` so subsequent logins report previously authenticated accounts.
/// - **Secret Key (`zpw_enk`)**: Decrypted 32-byte AES key string parsed via `crypto::parse_secret_key` and stored in `s.secret_key`.
/// - **Session Cookie (`zpw_sek`)**: Web authentication token extracted from `zpw_sek` or `account.zpw_sek`.
/// - **Display Name**: User display name resolved from `account.display_name` > `display_name` > `settings.profile.name`.
/// - **Send-to-Self ID (`send2me_id`)**: Conversation identifier for sending messages to oneself ("Cloud của tôi").
///
/// # Invariants
/// - **Partial Field Retention**: If the incoming payload only carries partial fields (e.g. key refresh without profile),
///   already-established credentials in `s.login` are retained rather than overwritten with empty values.
/// - **Expired Marker Reset**: Invokes `s.clear_expired()` to clear any stale refusal marker (#21).
/// - **Domain Routing Overrides**: Automatically calls [`Session::apply_server_info_wire`] to update WebSocket,
///   long-polling, and REST API service maps, then applies HTTPS-normalized `lp_chat` and `lp_control` host overrides.
pub fn apply_login_config(s: &mut Session, typed: &LoginConfigWireData) {
    let new_dkey = typed.dkey();
    let new_enk = typed.zpw_enk();
    let new_send2me_id = typed.send2me_id();
    let new_sek = typed.zpw_sek();
    let new_name = typed.display_name();

    if !new_enk.is_empty() {
        let raw = crate::crypto::parse_secret_key(&new_enk);
        s.secret_key = Some(raw);
    }
    if !new_sek.is_empty() {
        s.set_zpw_sek(new_sek.clone());
    }

    let mut current = s.login.take().unwrap_or_default();
    if !new_dkey.is_empty() {
        current.uin = new_dkey.to_string();
    }
    s.record_known_uid(&current.uin);
    if !new_enk.is_empty() {
        current.zpw_enk = new_enk.to_string();
    }
    if !new_sek.is_empty() {
        current.zpw_sek = new_sek.to_string();
    } else if current.zpw_sek.is_empty() {
        if let Some(sek) = &s.zpw_sek {
            current.zpw_sek = sek.clone();
        }
    }
    if !new_name.is_empty() {
        current.display_name = new_name.to_string();
    }
    if !new_send2me_id.is_empty() {
        current.send2me_id = new_send2me_id.to_string();
    }

    s.login = Some(current);

    // Domain overrides: apply server info and endpoint tables directly.
    s.apply_server_info_wire(&typed.server_info);
    // A real login response means the session is fresh: drop the "refused" marker so it
    // cannot leak into the new `session.json` (#21).
    s.clear_expired();
    if let Some(v) = typed.lp_chat() {
        s.domains.lp_chat = normalize_host(&v);
    }
    if let Some(v) = typed.lp_control() {
        s.domains.lp_control = normalize_host(&v);
    }
}

fn normalize_host(v: &str) -> String {
    if v.starts_with("http") {
        v.trim_end_matches('/').to_string()
    } else {
        format!("https://{}", v.trim_end_matches('/'))
    }
}
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn apply_login_config_captures_zpw_sek() {
        let mut s = Session::new(false, false, false).unwrap();
        let cfg = LoginConfigWireData::from_value(&serde_json::json!({
            "dkey": "12345",
            "zpw_enk": "dGVzdF9lbmtfMzJfYnl0ZXNfbG9uZ19hZXNfa2V5IQ==",
            "zpw_sek": "sek_abc_123",
            "display_name": "Test User"
        }));
        apply_login_config(&mut s, &cfg);
        assert_eq!(s.zpw_sek.as_deref(), Some("sek_abc_123"));
        let login = s.login.as_ref().unwrap();
        assert_eq!(login.zpw_sek, "sek_abc_123");
        assert_eq!(login.uin, "12345");
    }

    #[test]
    fn apply_login_config_clears_the_expired_marker() {
        let mut s = Session::new(false, false, false).unwrap();
        s.mark_expired();
        assert!(s.is_expired_marked());

        let cfg = LoginConfigWireData::from_value(&serde_json::json!({
            "dkey": "12345",
            "zpw_enk": "dGVzdF9lbmtfMzJfYnl0ZXNfbG9uZ19hZXNfa2V5IQ==",
            "zpw_sek": "sek_after_relogin",
        }));
        apply_login_config(&mut s, &cfg);

        // Keeping the marker would pin the next start to the login screen (#21).
        assert!(!s.is_expired_marked());
        assert_eq!(s.zpw_sek.as_deref(), Some("sek_after_relogin"));
    }

    #[test]
    fn apply_login_config_captures_nested_account_zpw_sek() {
        let mut s = Session::new(false, false, false).unwrap();
        let cfg = LoginConfigWireData::from_value(&serde_json::json!({
            "dkey": "12345",
            "zpw_enk": "dGVzdF9lbmtfMzJfYnl0ZXNfbG9uZ19hZXNfa2V5IQ==",
            "account": {
                "zpw_sek": "sek_nested_456",
                "display_name": "Nested User"
            }
        }));
        apply_login_config(&mut s, &cfg);
        assert_eq!(s.zpw_sek.as_deref(), Some("sek_nested_456"));
        let login = s.login.as_ref().unwrap();
        assert_eq!(login.zpw_sek, "sek_nested_456");
    }
}
