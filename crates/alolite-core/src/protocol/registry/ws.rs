#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ws_catalog_resolves_known_commands_and_rejects_unknown() {
        assert_eq!(cmd_name(AUTHEN), Some("AUTHEN"));
        assert_eq!(cmd_name(E2EE_SUBMIT_BUNDLE), Some("E2EE_SUBMIT_BUNDLE"));
        assert_eq!(cmd_name(SYNC_MESSAGE_REQUEST), Some("SYNC_MESSAGE_REQUEST"));
        assert_eq!(cmd_name(9999), None);
    }
}
